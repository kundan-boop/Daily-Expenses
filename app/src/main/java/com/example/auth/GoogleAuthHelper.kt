package com.example.auth

import android.app.Activity
import android.content.Context
import android.content.res.Resources
import android.util.Log
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.example.R
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.tasks.await
import kotlinx.coroutines.withContext

data class GoogleSignInAccountInfo(
    val uid: String,
    val displayName: String,
    val email: String,
    val photoUrl: String?
)

object GoogleAuthHelper {

    private const val TAG = "GoogleAuthHelper"

    fun getCurrentFirebaseUser(): FirebaseUser? {
        return try {
            FirebaseAuth.getInstance().currentUser
        } catch (_: Exception) {
            null
        }
    }

    fun getCurrentAccountInfo(): GoogleSignInAccountInfo? {
        val user = getCurrentFirebaseUser() ?: return null
        return GoogleSignInAccountInfo(
            uid = user.uid,
            displayName = user.displayName ?: "Google Account",
            email = user.email ?: "",
            photoUrl = user.photoUrl?.toString()
        )
    }

    /**
     * Resolves the OAuth Web Client ID generated by the Google Services plugin from google-services.json.
     */
    fun resolveWebClientId(context: Context): String? {
        return try {
            context.getString(R.string.default_web_client_id).trim().takeIf { it.isNotBlank() }
        } catch (_: Resources.NotFoundException) {
            null
        } catch (_: Exception) {
            null
        }
    }

    /**
     * Checks whether the Web Client ID from google-services.json is bundled in this build.
     */
    fun isClientConfigAvailable(context: Context): Boolean = !resolveWebClientId(context).isNullOrBlank()

    /**
     * Attempts silent auto sign-in on authorized Google accounts using GetGoogleIdOption
     * (single option per GetCredentialRequest for Android 16+ reliability).
     */
    suspend fun attemptAutoSignIn(context: Context): GoogleSignInAccountInfo? {
        getCurrentAccountInfo()?.let { return it }
        val serverClientId = resolveWebClientId(context) ?: return null
        return try {
            val googleIdOption = GetGoogleIdOption.Builder()
                .setFilterByAuthorizedAccounts(true)
                .setServerClientId(serverClientId)
                .setAutoSelectEnabled(true)
                .build()
            val request = GetCredentialRequest.Builder()
                .addCredentialOption(googleIdOption)
                .build()

            val credentialManager = CredentialManager.create(context)
            val result = credentialManager.getCredential(
                context = context,
                request = request
            )
            exchangeGoogleCredentialForFirebase(result.credential).getOrNull()
        } catch (_: Exception) {
            null
        }
    }

    /**
     * Signs into Firebase Authentication via Jetpack Credential Manager (GetSignInWithGoogleOption).
     * Never blocks local offline usage when cancelled or signed out.
     */
    suspend fun signInWithGoogle(activity: Activity): Result<GoogleSignInAccountInfo> {
        return try {
            val serverClientId = resolveWebClientId(activity)
                ?: return Result.failure(
                    IllegalStateException(
                        "Google Sign-In configuration missing (default_web_client_id). " +
                            "Verify google-services.json includes the OAuth Web Client (client_type 3) and matching SHA-1/SHA-256 keys."
                    )
                )

            val signInWithGoogleOption = GetSignInWithGoogleOption.Builder(serverClientId)
                .build()

            val request = GetCredentialRequest.Builder()
                .addCredentialOption(signInWithGoogleOption)
                .build()

            val credentialManager = CredentialManager.create(activity)
            val result = credentialManager.getCredential(
                context = activity,
                request = request
            )
            exchangeGoogleCredentialForFirebase(result.credential)
        } catch (e: GetCredentialCancellationException) {
            Log.w(TAG, "Google Sign-In cancelled or dismissed: ${e.message}", e)
            Result.failure(IllegalStateException("Google Sign-In cancelled"))
        } catch (e: NoCredentialException) {
            Log.w(TAG, "No Google credential available: ${e.message}", e)
            Result.failure(
                IllegalStateException(
                    "No Google account available on device. Add a Google account in device settings or check Play Services."
                )
            )
        } catch (e: GetCredentialException) {
            Log.e(TAG, "Credential Manager sign-in error: ${e.type} / ${e.message}", e)
            val msg = e.message.orEmpty()
            val friendly = if (msg.contains("10") || msg.contains("Developer", ignoreCase = true) || msg.contains("caller", ignoreCase = true)) {
                "Google Sign-In SHA-1/SHA-256 or Web Client ID mismatch. Add the APK signing SHA-1/SHA-256 in Firebase Console and refresh google-services.json."
            } else {
                e.localizedMessage ?: "Google Sign-In failed"
            }
            Result.failure(IllegalStateException(friendly, e))
        } catch (e: Exception) {
            Log.e(TAG, "Google Sign-In failed", e)
            Result.failure(e)
        }
    }

    private suspend fun exchangeGoogleCredentialForFirebase(
        credential: androidx.credentials.Credential
    ): Result<GoogleSignInAccountInfo> {
        return if (credential is CustomCredential &&
            credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
        ) {
            val googleIdTokenCredential = GoogleIdTokenCredential.createFrom(credential.data)
            val firebaseCredential = GoogleAuthProvider.getCredential(
                googleIdTokenCredential.idToken,
                null
            )
            val authResult = withContext(Dispatchers.IO) {
                FirebaseAuth.getInstance().signInWithCredential(firebaseCredential).await()
            }
            val user = authResult.user
                ?: return Result.failure(IllegalStateException("Firebase sign-in returned no user."))
            Result.success(
                GoogleSignInAccountInfo(
                    uid = user.uid,
                    displayName = user.displayName ?: googleIdTokenCredential.displayName ?: "Google User",
                    email = user.email ?: googleIdTokenCredential.id,
                    photoUrl = (user.photoUrl ?: googleIdTokenCredential.profilePictureUri)?.toString()
                )
            )
        } else {
            Result.failure(IllegalStateException("Unsupported credential type returned."))
        }
    }

    suspend fun signOut(context: Context) {
        try {
            FirebaseAuth.getInstance().signOut()
        } catch (_: Exception) {}
        try {
            CredentialManager.create(context).clearCredentialState(ClearCredentialStateRequest())
        } catch (_: Exception) {}
    }
}
